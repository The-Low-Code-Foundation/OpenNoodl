    '/** Add: appends the current Chunk, which is retained between pulses. */',
    'export function accumulatorAdd(state: AccumulatorState): StreamEvent[] {',
    '  const events: StreamEvent[] = [];',
    '  const chunk = state.pendingChunk;',
    "  if (chunk === '') {",
    "    // An empty chunk is a no-op, not an error: a stream's keep-alive frames are empty. Also the path after a refused chunk.",
    "    reportOutcome(events, 'unchanged');",
    '    return events;',
    '  }',
    '',
    '  state.buffer += chunk;',
    '',
    '  const capped = truncateHead(state.buffer, state.maxLength);',
    '  state.buffer = capped.text;',
    '  if (capped.dropped > 0) {',
    '    state.droppedCharacters += capped.dropped;',
    "    events.push({ kind: 'signal', name: 'overflowed' });",
    '  }',
    '',
    '  const split = splitDelimited(state.buffer, state.delimiter);',
    '  state.buffer = split.rest;',
    '',
    '  if (split.messages.length > 0) {',
    '    state.messages = state.messages.concat(split.messages);',
    '    state.lastMessage = split.messages[split.messages.length - 1];',
    '',
    '    const max = state.maxMessages;',
    '    if (max > 0 && state.messages.length > max) {',
    '      const dropped = state.messages.length - max;',
    '      state.messages = state.messages.slice(dropped);',
    '      state.droppedMessages += dropped;',
    "      events.push({ kind: 'signal', name: 'overflowed' });",
    '    }',
    '  }',
    '',
    '  // Message Received fires once per Add that completed at least one message, not once per message.',
    "  if (split.messages.length > 0) events.push({ kind: 'signal', name: 'messageReceived' });",
    "  events.push({ kind: 'signal', name: 'changed' });",
    '',
    "  reportOutcome(events, 'done');",
    '  return events;',
    '}',
    '',
    '/** Clear: empties the buffer, the messages and both dropped counts. */',
    'export function accumulatorClear(state: AccumulatorState): StreamEvent[] {',
    '  const events: StreamEvent[] = [];',
    '  // Read before the reset, not after.',
    '  const hadSomethingToClear =',
    '    state.buffer.length > 0 ||',
    '    state.messages.length > 0 ||',
    '    state.droppedCharacters > 0 ||',
    '    state.droppedMessages > 0 ||',
    '    !!state.error;',
    "  state.buffer = '';",
    '  state.messages = [];',
    "  state.lastMessage = '';",
    '  state.droppedCharacters = 0;',
    '  state.droppedMessages = 0;',
    "  state.error = '';",
    '',
    "  events.push({ kind: 'signal', name: 'cleared' });",
    "  reportOutcome(events, hadSomethingToClear ? 'done' : 'unchanged');",
    '  return events;',
    '}',

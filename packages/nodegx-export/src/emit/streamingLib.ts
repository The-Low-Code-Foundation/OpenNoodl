    '      raiseAppError({ code: event.code, message: event.message, nodeId: source.nodeId, nodeType, componentName: source.componentName });',
    "    } else if (event.kind === 'arm-timer') armTimer();",
    '    else if (host.timer !== null) {',
    '      clearTimeout(host.timer);',
    '      host.timer = null;',
    '    }',
    '  }',
    '}',

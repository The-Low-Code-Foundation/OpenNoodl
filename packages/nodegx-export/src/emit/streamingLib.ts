    '/** The Chunk setter: text and the primitives that read as text are accepted; anything else is refused and named. */',
    'export function accumulatorSetChunk(state: AccumulatorState, value: unknown): StreamEvent[] {',
    '  const events: StreamEvent[] = [];',
    '  const kind = typeof value;',
    '',
    '  if (value === undefined || value === null) {',
    "    state.pendingChunk = '';",
    "  } else if (kind === 'string') {",
    '    state.pendingChunk = value as string;',
    "  } else if (kind === 'number' || kind === 'boolean' || kind === 'bigint') {",
    '    state.pendingChunk = String(value);',
    '  } else {',
    "    state.pendingChunk = '';",
    '    accumulatorReportChunkError(state, describeBadChunk(value), events);',
    '    return events;',
    '  }',
    '',
    "  state.error = '';",
    '  return events;',
    '}',

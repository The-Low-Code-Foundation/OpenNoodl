/**
 * `src/lib/streaming.ts` — the streaming trio's host, emitted into the app (EXP-011 §58).
 *
 * {@link ./runTasksLib.ts}'s shape, one module over: a transcription of the runtime the three nodes have to
 * agree with, shipped only when a component keeps a `JSON Stream Parser`, a `Stream Buffer` or a `Text
 * Accumulator`. It transcribes `noodl-runtime/src/nodes/std-library/agent/stream-parsers.ts` (the pure cores —
 * `splitDelimited`, `scanJsonValues` with its string / escape / depth tracking and its waiting scalar,
 * `tryParseJson`, `truncateHead`, `utf8ByteLength`) and the three node files (`json-stream-parser.ts`,
 * `stream-buffer.ts`, `text-accumulator.ts`) as pure functions over a state object that return the ORDERED event
 * list the runtime would issue — every value-level signal, every outcome (`done` / `unchanged` / `failure`, then
 * `completed`, the raise before the `failure` pulse as `Node.reportOutcome` orders it), and the buffer's timer
 * instructions — so every boundary case is gradable under node, and three hooks that deliver those events.
 *
 * The data port is delivered with the pulse (`parse(chunk)`, `add(data)`: the setter, then the action); the config
 * ports are read off an options object every render (a present key goes through the setter's coercion, an
 * absent one keeps `initialize()`'s value). The value outputs are live getters over the state. The raises carry
 * the node's own provenance (`Node.raiseRuntimeError`'s three fields) through `./errors`.
 *
 * What differs, recorded in the module's own header: the setters run at the pulse rather than at delivery; a
 * wired `Data` counts as arrived; `flagOutputDirty` collapses into one re-render per invocation.
 */


    "/** Delivers one invocation's events in order: a signal to its listener, a raise to the channel, the timer instructions to the host. */",
    'function deliver(',
    '  events: StreamEvent[],',
    '  host: Host,',
    '  on: { current: Listeners },',
    '  source: StreamSource,',
    '  nodeType: string,',
    '  armTimer: () => void',

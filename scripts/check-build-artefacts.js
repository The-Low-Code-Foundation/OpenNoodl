#!/usr/bin/env node
/**
 * Fails if generated editor build output is tracked in git.
 *
 * REV-008. Until this check existed, `src/main/main.bundle.js` and
 * `src/editor/index.bundle.js` were committed build artefacts sitting in `src/`,
 * indistinguishable from source. A months-old bundle ran instead of the code
 * next to it, main-process edits did nothing in dev, and the editor opened a
 * black window — see dev-docs/reference/DEBUG-INFRASTRUCTURE.md.
 *
 * Usage:
 *   npm run check:artefacts
 *
 * Not a lint rule about file *names*: it lists the exact paths webpack writes, so a
 * legitimately-tracked file that merely looks generated is never flagged.
 */
const { execFileSync } = require('child_process');
const path = require('path');

const ROOT = path.join(__dirname, '..');

/**
 * Paths webpack writes, as git pathspecs. `:(glob)` is load-bearing — without it
 * git's default wildcard matching lets `*` cross `/`, so `packages/noodl-editor/*.svg`
 * would sweep up every real icon under `src/assets/`.
 */
const GENERATED = [
  'packages/noodl-editor/src/editor/index.bundle.js',
  'packages/noodl-editor/src/editor/index.bundle.js.map',
  'packages/noodl-editor/src/frames/viewer-frame/index.bundle.js',
  'packages/noodl-editor/src/frames/viewer-frame/index.bundle.js.map',
  'packages/noodl-editor/src/main/main.bundle.js',
  'packages/noodl-editor/src/main/main.bundle.js.map',
  ':(glob)packages/noodl-editor/*.bundle.js',
  ':(glob)packages/noodl-editor/*.bundle.js.map',
  ':(glob)packages/noodl-editor/*.worker.js',
  ':(glob)packages/noodl-editor/*.worker.js.map',
  ':(glob)packages/noodl-editor/*.svg',
  'packages/noodl-editor/tests/index.bundle.js',
  ':(glob)packages/noodl-editor/tests/*.bundle.js',
  ':(glob)packages/noodl-editor/tests/*.worker.js',
  ':(glob)packages/noodl-editor/tests/*.svg'
];

const tracked = execFileSync('git', ['ls-files', '--', ...GENERATED], { cwd: ROOT, encoding: 'utf8' })
  .split('\n')
  .filter(Boolean);

if (tracked.length === 0) {
  console.log('✓ no generated editor build artefacts are tracked');
  process.exit(0);
}

console.error(`✗ ${tracked.length} generated build artefact(s) are tracked in git:\n`);
for (const file of tracked.slice(0, 20)) console.error(`    ${file}`);
if (tracked.length > 20) console.error(`    … and ${tracked.length - 20} more`);
console.error(
  '\nThese are webpack output, regenerated by `npm run build:editor` and `npm run dev`.\n' +
    'Committing them lets a stale bundle run instead of the source beside it.\n' +
    'Untrack them with:\n\n' +
    `    git rm --cached ${tracked.length > 1 ? '<the files above>' : tracked[0]}\n`
);
process.exit(1);
